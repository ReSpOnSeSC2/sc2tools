/**
 * gen-build-definitions — writes lib/build-definitions.generated.json,
 * every build label the replay engine can emit, for /definitions.
 *
 *   npm run definitions:gen                      (from apps/web; runs Python)
 *   node scripts/gen-build-definitions.mjs export.json
 *
 * Source of truth: apps/replay-engine/core/build_definitions.py. Its
 * scripts/export_build_definitions.py prints a JSON export; this script
 * runs it with $PYTHON (else python3, else python), or reads a saved
 * export passed as the only argument. Each label's race and matchup come
 * from its prefix ("PvZ - …" → Protoss in PvZ, "Zerg - …" → Zerg in any
 * matchup), and a label's 8-worker patch name (5.0.16) is kept with it.
 * lib/build-definitions.ts lays the hand-written wording in
 * lib/build-definitions/*.ts over the engine's.
 *
 * lib/__tests__/buildDefinitionsParity.test.ts fails when an engine label
 * has no web entry, and the engine's tests/test_build_definitions_export.py
 * fails when this file no longer matches the engine: re-run the script.
 */
import { execFileSync } from "node:child_process";
import { readFileSync, writeFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";

const webRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");

/** apps/replay-engine, the package that owns the labels. */
export const ENGINE_ROOT = path.resolve(webRoot, "..", "replay-engine");

/** The engine module the labels come from (the parity test reads it too). */
export const ENGINE_DEFINITIONS_FILE = path.join(ENGINE_ROOT, "core", "build_definitions.py");

/** The file this script writes. */
export const GENERATED_FILE = path.join(webRoot, "lib", "build-definitions.generated.json");

const EXPORT_SCRIPT = path.join(ENGINE_ROOT, "scripts", "export_build_definitions.py");
const NAME_SEPARATOR = " - ";
const RACE_WORDS = new Set(["Protoss", "Terran", "Zerg"]);
const MATCHUP_RE = /^([PTZ])v([PTZ])$/;
const RACE_BY_LETTER = { P: "Protoss", T: "Terran", Z: "Zerg" };

const byCodeUnit = (a, b) => (a < b ? -1 : a > b ? 1 : 0);

/**
 * Race and matchup of an engine label, from its prefix.
 *
 * Example: `labelRaceAndMatchup("PvZ - Stargate into Glaives")`
 * → { race: "Protoss", matchup: "PvZ" }; `"Zerg - 12 Pool"` → { race: "Zerg", matchup: null }.
 */
export function labelRaceAndMatchup(name) {
  const at = name.indexOf(NAME_SEPARATOR);
  const prefix = at > 0 ? name.slice(0, at) : "";
  if (RACE_WORDS.has(prefix)) return { race: prefix, matchup: null };
  const matchup = MATCHUP_RE.exec(prefix);
  if (matchup) return { race: RACE_BY_LETTER[matchup[1]], matchup: prefix };
  throw new Error(
    `definitions:gen: "${name}" must start with a race or matchup ("Zerg - ", "PvZ - ")`,
  );
}

/**
 * The generated catalog for an engine export, sorted by name.
 *
 * Example: `buildGeneratedCatalog({ definitions: [{ name: "Zerg - 12 Pool",
 * description: "…" }], eightWorkerNames: { "Zerg - 12 Pool": "Zerg - 8 Pool" } })`
 * → { …, definitions: [{ name: "Zerg - 12 Pool", race: "Zerg", matchup: null,
 * description: "…", eightWorkerName: "Zerg - 8 Pool" }] }.
 */
export function buildGeneratedCatalog(payload) {
  if (!payload || !Array.isArray(payload.definitions) || payload.definitions.length === 0) {
    throw new Error("definitions:gen: the export has no definitions");
  }
  const eightWorkerNames = new Map(Object.entries(payload.eightWorkerNames ?? {}));
  for (const [name, patchName] of eightWorkerNames) {
    if (typeof patchName !== "string" || !patchName.trim()) {
      throw new Error(`definitions:gen: "${name}" has an empty patch name`);
    }
  }
  const seen = new Set();
  const definitions = payload.definitions.map((entry) => {
    const name = entry?.name;
    const description = entry?.description;
    if (typeof name !== "string" || !name.trim() || typeof description !== "string") {
      throw new Error(`definitions:gen: malformed entry ${JSON.stringify(entry)}`);
    }
    if (seen.has(name)) throw new Error(`definitions:gen: "${name}" is listed twice`);
    seen.add(name);
    const eightWorkerName = eightWorkerNames.get(name);
    return {
      name,
      ...labelRaceAndMatchup(name),
      description: description.trim(),
      ...(eightWorkerName ? { eightWorkerName } : {}),
    };
  });
  for (const name of eightWorkerNames.keys()) {
    if (!seen.has(name)) {
      throw new Error(`definitions:gen: patch name for unknown label "${name}"`);
    }
  }
  return {
    $comment:
      "Generated by scripts/gen-build-definitions.mjs from apps/replay-engine/core/build_definitions.py. Do not edit: run npm run definitions:gen.",
    definitions: definitions.sort((a, b) => byCodeUnit(a.name, b.name)),
  };
}

/** The file contents for an engine export. */
export function renderGeneratedCatalog(payload) {
  return `${JSON.stringify(buildGeneratedCatalog(payload), null, 2)}\n`;
}

function runExport() {
  const pythons = process.env.PYTHON ? [process.env.PYTHON] : ["python3", "python"];
  for (const python of pythons) {
    try {
      return execFileSync(python, [EXPORT_SCRIPT], {
        cwd: ENGINE_ROOT,
        encoding: "utf8",
        stdio: ["ignore", "pipe", "inherit"],
      });
    } catch (err) {
      if (err?.code === "ENOENT") continue;
      throw err;
    }
  }
  throw new Error(
    "definitions:gen: no Python found. Set PYTHON, or pass a saved export: node scripts/gen-build-definitions.mjs export.json",
  );
}

if (process.argv[1] && import.meta.url === pathToFileURL(path.resolve(process.argv[1])).href) {
  const [exportFile] = process.argv.slice(2);
  const payload = JSON.parse(exportFile ? readFileSync(exportFile, "utf8") : runExport());
  writeFileSync(GENERATED_FILE, renderGeneratedCatalog(payload));
  console.log(
    `${path.relative(webRoot, GENERATED_FILE)}: ${payload.definitions.length} engine labels`,
  );
}
