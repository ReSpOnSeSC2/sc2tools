#!/usr/bin/env node
/**
 * gen-sprite-icon-fit — measures how much of each pre-rendered 128 px
 * roster icon is actually opaque, and bakes the answer into
 * ``lib/spriteIconFit.generated.ts``.
 *
 * WHY THIS EXISTS
 *
 * The roster icons (``public/sprites/icons/<Name>_<red|blue>.webp``)
 * were framed per model by the Blender bake, and the framing is NOT
 * uniform: unit renders run edge to edge (Marine fills 98 % of the
 * frame, Thor 100 %) while structures were left a wide transparent
 * margin (Nexus 67 %, Armory 67 %, Dark Shrine 58 %). Dropped into a
 * fixed 22 px chip, that margin is dead space — the Nexus draws ~15 px
 * of pixels where the Marine beside it draws ~22 px, and reads as a
 * mis-sized icon rather than a smaller building.
 *
 * Nothing in the icon framing encodes real in-game scale — a Marine and
 * a Thor both fill their frame — so the margin carries no meaning and
 * can be scaled away. ``spriteIconScale`` in ``lib/spriteSheets.ts``
 * turns the fractions below into the CSS scale that does it.
 *
 * WHY NOT JUST RE-CROP THE ASSETS: the icons ship from R2 with a
 * one-year immutable cache and are content-addressed by filename (see
 * scripts/upload-sprites.mjs) — rewriting them in place would leave
 * every cached client on the old framing. Measuring at build time and
 * correcting in CSS needs no new asset round trip.
 *
 * Usage:
 *   node scripts/gen-sprite-icon-fit.mjs \
 *     [--icons public/sprites/icons] \
 *     [--out   lib/spriteIconFit.generated.ts]
 *
 * Re-run after a sprite re-bake. Only the ``_blue`` variant is measured:
 * the two colour variants are the same render with a different team
 * tint, so their alpha coverage is identical (asserted by
 * lib/__tests__/spriteIconFit.test.ts against the shipped assets when
 * they are present).
 */

import fs from "node:fs";
import path from "node:path";
import sharp from "sharp";

function argOf(flag, fallback) {
  const i = process.argv.indexOf(flag);
  return i >= 0 && process.argv[i + 1] ? process.argv[i + 1] : fallback;
}

const iconsDir = argOf("--icons", path.join("public", "sprites", "icons"));
const outFile = argOf("--out", path.join("lib", "spriteIconFit.generated.ts"));

/**
 * Alpha below this counts as empty. The renders carry a faint
 * anti-aliased halo a couple of levels above zero; measuring at alpha
 * > 0 would let that halo claim the whole frame and report every icon
 * as a perfect fit.
 */
const ALPHA_FLOOR = 8;

/** Opaque bounding box of one icon, as a fraction of the frame. */
async function measure(file) {
  const { data, info } = await sharp(file)
    .ensureAlpha()
    .raw()
    .toBuffer({ resolveWithObject: true });
  const { width, height, channels } = info;
  let minX = width;
  let minY = height;
  let maxX = -1;
  let maxY = -1;
  for (let y = 0; y < height; y++) {
    for (let x = 0; x < width; x++) {
      if (data[(y * width + x) * channels + 3] <= ALPHA_FLOOR) continue;
      if (x < minX) minX = x;
      if (x > maxX) maxX = x;
      if (y < minY) minY = y;
      if (y > maxY) maxY = y;
    }
  }
  if (maxX < 0) return null;
  // The chip is square, so the constraining axis is the longer one:
  // scaling by the WIDER of the two is what makes the drawn pixels
  // reach the chip edge without the other axis overflowing it.
  const span = Math.max(maxX - minX + 1, maxY - minY + 1);
  return span / Math.max(width, height);
}

async function main() {
  if (!fs.existsSync(iconsDir)) {
    console.error(
      `gen-sprite-icon-fit: no icon directory at ${iconsDir}\n` +
        "The renders are not in git — pull them from R2 (or point --icons " +
        "at the Blender bake output) before regenerating.",
    );
    process.exit(1);
  }
  const files = fs
    .readdirSync(iconsDir)
    .filter((f) => f.endsWith("_blue.webp"))
    .sort();
  if (files.length === 0) {
    console.error(`gen-sprite-icon-fit: no *_blue.webp icons in ${iconsDir}`);
    process.exit(1);
  }

  const rows = [];
  for (const file of files) {
    const fill = await measure(path.join(iconsDir, file));
    if (fill === null) {
      console.warn(`gen-sprite-icon-fit: ${file} is fully transparent, skipped`);
      continue;
    }
    rows.push([file.slice(0, -"_blue.webp".length), Math.round(fill * 1000) / 1000]);
  }

  const body = rows.map(([name, fill]) => `  ${name}: ${fill},`).join("\n");
  const out = `/**
 * GENERATED by scripts/gen-sprite-icon-fit.mjs — do not edit by hand.
 *
 * Sheet name → the fraction of the 128 px roster icon its opaque
 * pixels actually span, on the longer axis. 1 means the render reaches
 * the frame edge; 0.67 means a third of the frame is transparent
 * margin. Consumed by \`\`spriteIconScale\`\` in lib/spriteSheets.ts.
 *
 * Measured from the _blue variant; the _red render is the same model
 * with a different team tint and measures identically.
 */

export const SPRITE_ICON_FILL: Readonly<Record<string, number>> = {
${body}
};
`;
  fs.mkdirSync(path.dirname(outFile), { recursive: true });
  fs.writeFileSync(outFile, out);
  console.log(`gen-sprite-icon-fit: wrote ${rows.length} entries to ${outFile}`);
}

main().catch((err) => {
  console.error(err);
  process.exit(1);
});
