/** Offline-only picker catalog. Bundling the existing metadata at generation
 * time keeps balance profiles out of the lazy editor's runtime dependency. */
import { readFileSync, writeFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { createRequire } from "node:module";
import { build } from "esbuild";
const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
export const GENERATED_FILE = path.join(root, "lib/buildTokens.ts");
const compare = (a, b) => a < b ? -1 : a > b ? 1 : 0;

export async function buildTokenCatalog() {
  const result = await build({
    stdin: { resolveDir: root, contents: `export{unitCostCatalog}from'./lib/sc2-units';export{getIconPath}from'./lib/sc2-icons';export{PROXY_ELIGIBLE_BUILDINGS}from'./lib/build-rules';export{humanizeRuleEntity}from'./lib/build-rules-copy';export{resolveProfile}from'./lib/sc2-patch/profiles';export{BUILD_TOKEN_UPGRADE_NAMES}from'./lib/buildTokenUpgrades';` },
    bundle: true, write: false, format: "cjs", platform: "node", alias: { "@": root }, logLevel: "silent",
  });
  const metadata = { exports: {} };
  // This executes only the repository's bundled pure metadata, never input or
  // a provider response. No generated/runtime module needs eval or Node APIs.
  new Function("module", "exports", "require", result.outputFiles[0].text)(metadata, metadata.exports, createRequire(import.meta.url));
  const { unitCostCatalog, getIconPath, PROXY_ELIGIBLE_BUILDINGS, humanizeRuleEntity, resolveProfile, BUILD_TOKEN_UPGRADE_NAMES } = metadata.exports;
  const catalog = new Map(), units = { ...unitCostCatalog("before"), ...unitCostCatalog("after") };
  const profile = resolveProfile("lotv-base"), morphs = new Set(["Baneling", "Ravager", "Lurker", "LurkerMP", "BroodLord", "Overseer", "OverlordTransport", "Archon", "Lair", "Hive", "GreaterSpire", "OrbitalCommand", "PlanetaryFortress", "WarpGate", "LurkerDen"]);
  for (const [name, def] of Object.entries(profile.units)) if (def.morphFrom) morphs.add(name);
  const add = (noun, verb, race, kind, proxyEligible = false) => {
    if (!["Protoss", "Terran", "Zerg"].includes(race) || !/^[A-Za-z][A-Za-z0-9]*$/.test(noun)) return;
    const token = `${verb}${noun}`, entity = humanizeRuleEntity(token), label = verb === "Train" || verb === "Morph" ? `${verb} ${entity}` : entity;
    catalog.set(token, { token, label, entity: noun, race, kind, proxyEligible, icon: getIconPath(noun, kind) });
  };
  for (const [name, def] of Object.entries(units)) {
    const kind = def.isBuilding || PROXY_ELIGIBLE_BUILDINGS.has(name) ? "building" : "unit";
    add(name, "Build", def.race, kind, PROXY_ELIGIBLE_BUILDINGS.has(name));
    if (kind === "unit") add(name, "Train", def.race, kind);
    if (morphs.has(name)) add(name, "Morph", def.race, kind);
  }
  for (const [race, names] of Object.entries(BUILD_TOKEN_UPGRADE_NAMES)) for (const name of names) add(name, "Research", race, "upgrade");
  for (const [name, def] of Object.entries(profile.upgrades)) add(name, "Research", def.race, "upgrade");
  // Old replay timelines expose these research events as bare Build tokens.
  for (const name of ["overlordspeed", "zerglingmovementspeed", "zerglingattackspeed"]) add(name, "Build", "Zerg", "upgrade");
  return [...catalog.values()].sort((a, b) => compare(a.race, b.race) || compare(a.kind, b.kind) || compare(a.label, b.label) || compare(a.token, b.token));
}
export function renderBuildTokens(rows) {
  return `// Generated by scripts/gen-build-tokens.mjs. Do not hand edit.\nexport type BuildTokenRace = "Protoss" | "Terran" | "Zerg";\nexport interface BuildToken { token: string; label: string; entity: string; race: BuildTokenRace; kind: "building" | "unit" | "upgrade"; proxyEligible: boolean; icon: string | null }\nexport const BUILD_TOKENS: readonly BuildToken[] = [\n${rows.map(row => `  ${JSON.stringify(row)},`).join("\n")}\n];\nconst byToken = new Map(BUILD_TOKENS.map(row => [row.token, row]));\nexport const getBuildToken = (value: string): BuildToken | undefined => byToken.get(value);\nexport const isKnownBuildToken = (value: string): boolean => byToken.has(value);\n`;
}
if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const rows = await buildTokenCatalog(), source = renderBuildTokens(rows);
  if (process.argv.includes("--check")) {
    if (readFileSync(GENERATED_FILE, "utf8").replace(/\r\n/g, "\n") !== source) throw new Error("buildTokens.ts is stale: run node scripts/gen-build-tokens.mjs");
  } else writeFileSync(GENERATED_FILE, source);
  console.log(`buildTokens.ts: ${rows.length} known actions`);
}
