/**
 * ReplayDemo — landing-page "drop a replay, see the real dossier" CTA.
 *
 * With Instant Analysis enabled for everyone, real intent loads a private
 * one-file browser session. No replay bytes/payload reach the API. The old
 * rate-limited server path remains only for the one-release flag-off
 * compatibility window; browser failures never fall through to it.
 *
 * On success we open the rich BuildEditorModal in demoMode so the
 * visitor can experience the real "Save as new build" template:
 * source-replay timeline, rule promotion, basics editing, strategy
 * notes — everything except the actual save (which is gated behind
 * sign-up). This is closer to what they'll actually do once signed
 * in than the read-only dossier we used to ship here.
 *
 * No mock data — if the upload fails, we surface the failure and a
 * sign-up CTA instead of pretending we know what's in the file.
 */

interface PreviewError {
  code: string;
  message: string;
  /** Server-assigned correlation ID (`x-request-id` response header
   *  or `error.requestId` body field). Surfaced in the modal's
   *  technical-details disclosure so a user can paste it into a bug
   *  report and we can grep the server logs for the same trace. */
  requestId?: string;
  /** HTTP status code returned by the API. Recorded so the
   *  technical-details disclosure can show e.g. "HTTP 502" alongside
   *  the application-level code, since they encode different things
   *  (transport vs domain). */
  httpStatus?: number;
}

